#!/usr/bin/env python3
"""Generate the round17 per-render-job template from the round16 profile1 input.

The round16 12-BO linear64 job (captured Apple helper graph + native user
draw) is split into:

* template bytes: helper programs, helper PPP/PDS data, context scratch,
  prologue VDM (two skip links + dead helper draws), clear/EOT programs and
  descriptors.  These are copied verbatim into every recorded render job;
* generated ranges: every byte that depends on the application's pipeline,
  draws, render area, clear colour or target.  They are zeroed here and the
  Mesa recorder must regenerate them.  Re-recording the round16 triangle
  with the profile1 placement must reproduce the round16 BOs exactly;
* the epilogue (varying reset, VDM PDS update, four-vertex never-pass
  rectangle, PPP terminate) as an item list, because its position follows
  the user draws.

No device access.  Output: src/imagination/vulkan/g5p/g5p_job_template.h in
the round17 Mesa worktree (or --out).
"""
import argparse
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'build/gpu-userspace/round16-input'
OUT = ROOT / 'third_party/mesa-g5p-gfx/src/imagination/vulkan/g5p/g5p_job_template.h'

ARENAS = ['code', 'static', 'state', 'scratch', 'quad', 'ppp', 'scissor', 'vdm', 'pool7', 'pool8']
PROFILE_ONLY = ['vertices', 'target']

# Generated ranges (arena, offset, size). Everything else is template.
GENERATED = [
    ('code', 0x22c0, 0x20),    # FS USC, first pipeline (profile1 slot)
    ('code', 0x2340, 4),       # fragment uniform/texture PDS (HALT)
    ('code', 0x23c0, 4),       # varying PDS copy 0 (HALT)
    ('code', 0x2440, 8),       # fragment PDS data (DOUTU src0)
    ('code', 0x2460, 4),       # fragment PDS code (DOUTU.end)
    ('code', 0x2540, 70),      # VS USC
    ('code', 0x2680, 12),      # vertex fetch PDS copy 0
    ('static', 0x21e0, 24),    # fragment PPP state, variant 0
    ('static', 0x2f60, 16),    # varying-format PPP block
    ('state', 0x2c0, 0x40),    # draw0 vertex fetch data + epilogue VS data
    ('state', 0x948, 0x2c),    # clear floats + 24-byte PBE + pad dword
    ('scratch', 0x63e8, 36),   # draw0 region clip + viewport
    ('ppp', 0xe0, 0xa0),       # user draw PPP blocks + epilogue blocks
    ('scissor', 0, 8),         # draw0 ISP depth-bias/scissor index block
    ('vdm', 0x1b8, 0xd0),      # user draws + epilogue + terminate
]

PROLOGUE_END = 0x1b8
EPILOGUE = 0x224
TERMINATE_PPP = 0x27c
TERMINATE = 0x284


def need(ok, msg):
    if not ok:
        raise SystemExit('template: ' + msg)


def words(data, off, n):
    return list(struct.unpack_from('<%dI' % n, data, off))


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--src', type=Path, default=SRC)
    p.add_argument('--out', type=Path, default=OUT)
    a = p.parse_args()
    m = json.loads((a.src / 'manifest.json').read_text())
    bos = {b['name']: b for b in m['bos']}
    data = {}
    for b in m['bos']:
        raw = (a.src / b['file']).read_bytes()
        need(len(raw) == b['size'], 'size ' + b['name'])
        need(hashlib.sha256(raw).hexdigest() == b['sha256'], 'hash ' + b['name'])
        data[b['name']] = bytearray(raw)
    vdm = data['vdm']
    need(m['vdm']['va'] == bos['vdm']['va'] and m['vdm']['size'] == 0x288, 'VDM geometry')
    need(words(vdm, TERMINATE, 1) == [0xc0000000], 'terminate word')
    # Epilogue item list, decoded from the actual stream (layout asserted).
    ep = words(vdm, EPILOGUE, (TERMINATE_PPP - EPILOGUE) // 4)
    need(ep[0:2] == [0x00000403, 0x000261a0], 'epilogue varying reset reference')
    need(ep[2:5] == [0x20000001, 0x00002240, 0x00002140], 'epilogue VDM PDS update')
    need(ep[5:9] == [0x44002f80, 0x000021c0, 0x00000004, 0x00001082], 'epilogue VS state')
    need(ep[9:11] == [0x48002f80, 0x000302e0], 'epilogue VS data')
    ppp_refs = [(ep[11 + 2 * i] >> 8 & 0xff, ((ep[11 + 2 * i] & 0xff) << 32) | ep[12 + 2 * i]) for i in range(3)]
    need(ppp_refs == [(14, 0x10008c11c), (6, 0x10008c154), (2, 0x10008c16c)], 'epilogue PPP refs')
    need(ep[17:22] == [0x6e440900, 4, 0, 0, 0x1fe], 'epilogue rectangle draw')
    ppp_blocks = [words(data['ppp'], va - bos['ppp']['va'], n) for n, va in ppp_refs]
    term = words(vdm, TERMINATE_PPP, 2)
    need(term == [0x00000301, 0x0008c174], 'terminate PPP ref')
    need(words(data['ppp'], 0x174, 3) == [0x02000000, 0x00040001, 0], 'terminate PPP block (64x64)')
    ep_vs_data = bytes(data['state'][0x2e0:0x300])
    need(ep_vs_data == struct.pack('<QQQQ', bos['quad']['va'], 0x1000002080, 0x80000004, 16), 'epilogue VS data')
    # Zero all generated ranges; they must be regenerated by the recorder.
    for name, off, size in GENERATED:
        data[name][off:off + size] = bytes(size)
    for name in ('pool7', 'pool8'):
        need(not any(data[name]), name + ' must be a zero allocation')
    lines = ['/* SPDX-License-Identifier: MIT */',
             '/* Generated by tools/gpu-userspace/render-round17-template.py from',
             ' * build/gpu-userspace/round16-input (manifest %s).' % hashlib.sha256((a.src / 'manifest.json').read_bytes()).hexdigest()[:16],
             ' * Captured Apple helper graph and clear/EOT programs with every',
             ' * pipeline/draw/target-dependent byte removed. Do not edit. */',
             '#ifndef G5P_JOB_TEMPLATE_H', '#define G5P_JOB_TEMPLATE_H', '#include <stdint.h>',
             'struct g5p_tpl_arena { const char *name; uint64_t va; uint32_t size, roles; uint8_t fill; };',
             'struct g5p_tpl_segment { uint32_t arena, offset, size; const uint8_t *data; };',
             'enum g5p_tpl_arena_id {']
    for i, name in enumerate(ARENAS + PROFILE_ONLY):
        lines.append('   G5P_TPL_%s = %d,' % (name.upper(), i))
    lines.append('   G5P_TPL_ARENA_COUNT = %d, G5P_TPL_JOB_ARENAS = %d,' % (len(ARENAS) + len(PROFILE_ONLY), len(ARENAS)))
    lines.append('};')
    lines.append('static const struct g5p_tpl_arena g5p_tpl_arenas[] = {')
    for name in ARENAS + PROFILE_ONLY:
        b = bos[name]
        lines.append('   {"%s", 0x%xULL, 0x%x, %d, 0x%x},' % (name, b['va'], b['size'], b.get('gpu_access', 1), b['fill']))
    lines.append('};')
    segs = []
    for ai, name in enumerate(ARENAS):
        buf = data[name]
        i = 0
        while i < len(buf):
            if not buf[i]:
                i += 1
                continue
            j = i
            while j < len(buf) and (any(buf[j:j + 32])):
                j += 1
            start, end = i & ~3, (j + 3) & ~3
            segs.append((ai, start, bytes(buf[start:end])))
            i = end
    for k, (ai, off, b) in enumerate(segs):
        lines.append('static const uint8_t g5p_tpl_s%d[%d] = {%s};' % (k, len(b), ','.join('0x%02x' % x for x in b)))
    lines.append('static const struct g5p_tpl_segment g5p_tpl_segments[] = {')
    for k, (ai, off, b) in enumerate(segs):
        lines.append('   {%d, 0x%x, %d, g5p_tpl_s%d},' % (ai, off, len(b), k))
    lines.append('};')
    lines.append('#define G5P_TPL_SEGMENT_COUNT %d' % len(segs))
    lines.append('/* Stream layout of the captured job. */')
    lines.append('#define G5P_TPL_VDM_PROLOGUE 0x%x /* user draws start here */' % PROLOGUE_END)
    lines.append('#define G5P_TPL_PPP_POOL 0xe0 /* user PPP blocks start here */')
    lines.append('#define G5P_TPL_STATE_POOL 0x2c0 /* per-draw PDS data starts here */')
    lines.append('#define G5P_TPL_STATE_POOL_END 0x800 /* clear/EOT descriptors follow */')
    lines.append('#define G5P_TPL_VIEWPORT_POOL 0x63e8 /* scratch: after the 4 markers */')
    lines.append('#define G5P_TPL_SCISSOR_POOL 0x0')
    lines.append('#define G5P_TPL_CLEAR_FLOATS 0x948 /* state */')
    lines.append('#define G5P_TPL_PBE 0x958 /* state: 24 bytes + zero dword */')
    lines.append('/* Epilogue VDM, verbatim except the noted operands. */')
    lines.append('static const uint32_t g5p_tpl_epilogue_head[] = {%s}; /* varying reset (static+0x21a0) .. VDM PDS update .. VS state */'
                 % ', '.join('0x%08x' % w for w in ep[0:9]))
    lines.append('#define G5P_TPL_EPILOGUE_VS_DATA_STATE0 0x%08x /* + B-relative PDS data address */' % ep[9])
    for i, blk in enumerate(ppp_blocks):
        lines.append('static const uint32_t g5p_tpl_epilogue_ppp%d[] = {%s};' % (i, ', '.join('0x%08x' % w for w in blk)))
    lines.append('static const uint32_t g5p_tpl_epilogue_draw[] = {%s}; /* 4-vertex never-pass strip */' % ', '.join('0x%08x' % w for w in ep[17:22]))
    lines.append('static const uint8_t g5p_tpl_epilogue_vs_data[32] = {%s}; /* quad VA, USC 0x2080 */' % ','.join('0x%02x' % x for x in ep_vs_data))
    b16 = m['background_words']
    lines.append('static const uint32_t g5p_tpl_background[8] = {%s};' % ', '.join('0x%x' % w for w in b16))
    lines.append('static const uint32_t g5p_tpl_eot[3] = {%s};' % ', '.join('0x%x' % w for w in m['eot_words']))
    cd = m['context_descriptors']
    for k in ('record_context_pds0', 'record_context_pds1', 'record_resume_pds0', 'record_resume_pds1'):
        lines.append('static const uint32_t g5p_tpl_%s[%d] = {%s};' % (k[7:], len(cd[k]), ', '.join('0x%x' % w for w in cd[k])))
    sf = m['context_record_fields']
    lines.append('static const uint64_t g5p_tpl_scratch_fields[6] = {%s};' % ', '.join('0x%xULL' % sf[k] for k in ('0x48', '0x50', '0x58', '0x60', '0x98', '0xa0')))
    lines.append('#endif')
    a.out.write_text('\n'.join(lines) + '\n')
    print('wrote %s: %d segments, %d template bytes' % (a.out, len(segs), sum(len(s[2]) for s in segs)))


if __name__ == '__main__':
    main()
